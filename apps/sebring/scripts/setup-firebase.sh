#!/usr/bin/env bash
# Configure Firebase for the Sebring app: pick/create project, web app, write .env, deploy rules.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

ENV_FILE="$ROOT/.env"

echo "=== Sebring Firebase setup ==="
echo ""

if ! command -v firebase >/dev/null 2>&1; then
  echo "Installing firebase-tools..."
  npm install -g firebase-tools@latest
fi

echo "Checking Firebase login..."
if ! firebase projects:list >/dev/null 2>&1; then
  echo ""
  echo "Firebase login required. Opening browser..."
  firebase login --reauth
fi

echo ""
echo "Available projects:"
firebase projects:list

echo ""
read -r -p "Firebase project ID for Sebring (existing or new): " PROJECT_ID

if ! firebase projects:list 2>/dev/null | grep -q "$PROJECT_ID"; then
  read -r -p "Project '$PROJECT_ID' not found. Create it? [y/N] " CREATE
  if [[ "${CREATE,,}" == "y" ]]; then
    firebase projects:create "$PROJECT_ID" --display-name "Sebring 350 Restoration"
  else
    echo "Aborted."
    exit 1
  fi
fi

firebase use "$PROJECT_ID" --add

echo ""
echo "Initializing Firestore + Storage (uses existing rules in this folder)..."
firebase init firestore storage --project "$PROJECT_ID" --non-interactive 2>/dev/null || true

# Ensure rules files are used (already in repo)
firebase deploy --only firestore:rules,storage:rules --project "$PROJECT_ID"

echo ""
echo "Creating web app (if needed)..."
APP_ID="$(firebase apps:list WEB --project "$PROJECT_ID" --json 2>/dev/null | node -e "
const d=JSON.parse(require('fs').readFileSync(0,'utf8'));
const apps=d.result?.apps ?? d.result ?? [];
const hit=apps.find(a=>a.displayName?.includes('Sebring')||a.platform==='WEB');
console.log(hit?.appId ?? '');
" 2>/dev/null || true)"

if [[ -z "$APP_ID" ]]; then
  firebase apps:create WEB "Sebring Site" --project "$PROJECT_ID"
fi

echo ""
echo "Fetching web SDK config..."
SDK_JSON="$(firebase apps:sdkconfig WEB --project "$PROJECT_ID" --json)"

node -e "
const sdk = JSON.parse(process.argv[1]).result?.sdkConfig ?? JSON.parse(process.argv[1]);
const lines = [
  '# Generated by scripts/setup-firebase.sh',
  'PUBLIC_FIREBASE_API_KEY=' + sdk.apiKey,
  'PUBLIC_FIREBASE_AUTH_DOMAIN=' + sdk.authDomain,
  'PUBLIC_FIREBASE_PROJECT_ID=' + sdk.projectId,
  'PUBLIC_FIREBASE_STORAGE_BUCKET=' + sdk.storageBucket,
  'PUBLIC_FIREBASE_MESSAGING_SENDER_ID=' + sdk.messagingSenderId,
  'PUBLIC_FIREBASE_APP_ID=' + sdk.appId,
  '',
];
require('fs').writeFileSync('$ENV_FILE', lines.join('\n'));
console.log('Wrote $ENV_FILE');
" "$SDK_JSON"

echo ""
echo "Enable Google Sign-In in Firebase Console → Authentication → Sign-in method."
echo ""
echo "Next steps:"
echo "  1. cd apps/sebring/functions && npm install && cd .."
echo "  2. firebase functions:secrets:set GEMINI_API_KEY"
echo "  3. firebase deploy --only functions"
echo "  4. npm run deploy    # rebuild + rsync (PUBLIC_ vars are baked in at build time)"
echo ""
echo "Done."
